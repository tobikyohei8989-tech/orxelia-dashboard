import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
import test from 'node:test';
test('development intake, legal approval, sales approval and priority updates',async t=>{
  const db = new PGlite();
  t.after(()=>db.close());
  const owner='00000000-0000-0000-0000-000000000001';
  const outsider='00000000-0000-0000-0000-000000000002';
  const proposal='00000000-0000-0000-0000-000000000003';
  await db.exec(`create role anon; create role authenticated; create schema auth;
  create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
  grant usage on schema auth to authenticated;
  create table public.orxelia_proposals(id uuid primary key, owner_id uuid not null, revision_number integer, status text not null default 'awaiting_first_approval', updated_at timestamptz default now(), created_at timestamptz default now(), title text, design_status text default 'ready', approved_at timestamptz, final_approved_at timestamptz, revision_request text, prototype_revision_request text, sales_review jsonb, brief jsonb, prototype_html text, test_report jsonb);
  grant select on public.orxelia_proposals to authenticated;
  create function public.fixture_transition(proposal_id uuid,next_status text) returns void language sql security definer set search_path='' as $$ update public.orxelia_proposals set status=next_status where id=proposal_id and owner_id=auth.uid() $$;
  insert into public.orxelia_proposals (id,owner_id,revision_number) values ('${proposal}','${owner}',1);`);
  await db.exec(readFileSync(new URL('../../database/changes/dashboard_legal_review.sql',import.meta.url),'utf8'));
  await db.exec(readFileSync(new URL('../../database/changes/dashboard_development_request.sql',import.meta.url),'utf8'));
  await db.exec(readFileSync(new URL('../../database/changes/dashboard_proposal_transition.sql',import.meta.url),'utf8'));
  await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','${owner}',false);`);
  const checks=Object.fromEntries(['regulation','trademark','copyright','terms','privacy','sales','security'].map(key=>[key,{status:'passed',evidence:'official document',reviewer:'reviewer',reviewedAt:'2026-11-11'}]));
  const save=async (previous,revision,entries,risks=[],id=proposal) => (await db.query('select version,eligible from public.orxelia_save_legal_review($1,$2,$3,$4,$5)',[id,previous,revision,JSON.stringify(entries),JSON.stringify(risks)])).rows[0];
  const transition=(id,status)=>db.query('select public.fixture_transition($1,$2)',[id,status]);
  const approve=()=>db.query("select public.orxelia_proposal_transition($1,'approve_development',null::text)",[proposal]);
  await assert.rejects(approve(),/法務審査を完了/);
  const first=await save(null,1,{...checks,privacy:{status:'expert_review'}});
  assert.equal(first.eligible,false);
  const second=await save(first.version,1,checks);
  assert.equal(second.eligible,true);
  await assert.rejects(approve(),/非公開試作/);
  await assert.rejects(db.exec("update public.orxelia_proposals set test_report='{}'"),/permission denied/);
  await db.exec(`reset role; update public.orxelia_proposals set prototype_html='<html>trial</html>', test_report='{"preapproval_trial":{"passed":true,"design_revision":2}}' where id='${proposal}'; set role authenticated;`);
  await assert.rejects(approve(),/非公開試作/);
  await db.exec(`reset role; update public.orxelia_proposals set test_report='{"preapproval_trial":{"passed":true,"design_revision":1}}' where id='${proposal}'; set role authenticated;`);
  await approve();
  assert.equal((await db.query('select review_version from public.orxelia_legal_development_approvals')).rows[0].review_version,second.version);
  const blocked=await save(second.version,1,checks,[{severity:'high',status:'open',detail:'unresolved'}]);
  assert.equal(blocked.eligible,false);
  assert.equal((await db.query('select status from public.orxelia_proposals')).rows[0].status,'awaiting_first_approval');
  await assert.rejects(approve(),/法務審査を完了/);
  await assert.rejects(transition(proposal,'developing'),/開発承認/);
  await assert.rejects(save(first.version,1,checks),/別の端末/);
  await assert.rejects(save(blocked.version,2,checks),/デザインが更新/);
  await assert.rejects(db.exec('update public.orxelia_legal_reviews set eligible=true'),/permission denied/);
  assert.equal((await db.query('select count(*)::int as count from public.orxelia_legal_reviews')).rows[0].count,3);
  const requestId='00000000-0000-0000-0000-000000000004';
  const submit = async (title='New request') => (await db.query('select public.orxelia_request_development($1,$2,$3,$4,$5,$6) as result',[requestId,title,'purpose','audience','features','references'])).rows[0].result;
  await assert.rejects(submit('  '),/必須項目/);
  const submitted=await submit();
  assert.equal(submitted.id,requestId);
  assert.equal(submitted.status,'awaiting_selection');
  assert.deepEqual(await submit(),submitted);
  await db.exec(`select set_config('request.jwt.claim.sub','${outsider}',false);`);
  assert.equal((await db.query('select count(*)::int as count from public.orxelia_legal_reviews')).rows[0].count,0);
  await assert.rejects(save(blocked.version,1,checks),/案件が見つかりません/);
  await assert.rejects(submit(),/依頼を保存できません/);
  await assert.rejects(db.query('select * from public.orxelia_set_proposal_priority($1)',[proposal]),/対象の案件/);
  await db.exec(`reset role; update public.orxelia_proposals set status='awaiting_final_approval',
    sales_review='{"recommendation":"ready"}' where id='${proposal}';
    set role authenticated; select set_config('request.jwt.claim.sub','${owner}',false);`);
  const approveSales=()=>db.query("select public.orxelia_proposal_transition($1,'approve_sales',null::text)",[proposal]);
  await assert.rejects(approveSales(),/法務審査/);
  assert.equal((await save(blocked.version,1,checks)).eligible,true);
  await approveSales();
  assert.equal((await db.query('select status from public.orxelia_proposals where id=$1',[proposal])).rows[0].status,'final_approved');
  await db.query('select * from public.orxelia_set_proposal_priority($1)',[proposal]);
  await db.query('select * from public.orxelia_set_proposal_priority($1)',[submitted.id]);
  assert.deepEqual((await db.query("select id from public.orxelia_proposals where brief->>'priority_rank'='1'")).rows,[{id:submitted.id}]);
  console.log('PASS: PostgreSQL migration, review states, risk hold, stale edits, revision guard, immutable history, and cross-owner authorization');
});
