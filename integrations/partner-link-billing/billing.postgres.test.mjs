import assert from 'node:assert/strict';
import fs from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
import test from 'node:test';
test('notification persistence, retries, payment and access lifecycles',async t=>{
  const db=new PGlite();
  t.after(()=>db.close());
  const owner='00000000-0000-0000-0000-000000000001';
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    grant usage on schema auth to authenticated;
    insert into auth.users values ('${owner}');
    select set_config('request.jwt.claim.sub','${owner}',false);`);
  const root=new URL('./',import.meta.url);
  for(const file of ['customer-management.sql','registration.sql','queue.sql','reconcile.sql','worker.sql'])
    await db.exec(fs.readFileSync(new URL(file,root),'utf8'));
  const customer=(await db.query("select public.orxelia_register_billing_customer('テスト会社') id")).rows[0].id;
  await db.query("insert into public.orxelia_billing_contracts(customer_id,app_id,stripe_subscription_id,status,monthly_amount_jpy) values ($1,'partner-link','sub_test','incomplete',3980)",[customer]);
  const contract=(await db.query('select id from public.orxelia_billing_contracts')).rows[0].id;
  await db.exec("insert into public.partner_link_stripe_events(event_id,event_type,stripe_created,livemode,payload) values ('evt_test','invoice.paid',1,false,'{}')");
  await db.exec('set role authenticated');
  await assert.rejects(db.query('select public.partner_link_claim_stripe_event(false)'),/permission denied/);
  await assert.rejects(db.query("select public.orxelia_record_billing_risk('evt_test',$1,'refund','[]')",[contract]),/permission denied/);
  await db.exec('set role service_role');
  const claim=(await db.query('select * from public.partner_link_claim_stripe_event(false)')).rows[0];
  assert.equal(claim.event_id,'evt_test');
  assert.equal((await db.query('select * from public.partner_link_claim_stripe_event(false)')).rows.length,0);
  assert.equal((await db.query('select public.partner_link_finish_stripe_event($1,$2,true) finished',['evt_test',owner])).rows[0].finished,false);
  assert.equal((await db.query('select public.partner_link_finish_stripe_event($1,$2,false) finished',['evt_test',claim.claim_token])).rows[0].finished,true);
  assert.equal((await db.query('select * from public.partner_link_claim_stripe_event(false)')).rows.length,0);
  await db.query("update public.partner_link_stripe_events set retry_after=now()-interval '1 second'");
  const next=(await db.query('select * from public.partner_link_claim_stripe_event(false)')).rows[0];
  assert.notEqual(next.claim_token,claim.claim_token);
  const now=Math.floor(Date.now()/1000);
  const snapshot={status:'active',trial_until:null,paid_until:now+86400,cancel_at:null,payments:[{id:'in_test',amount:3980,paid_at:now}]};
  await db.query('select public.orxelia_save_subscription_snapshot($1,0,$2)',[contract,JSON.stringify(snapshot)]);
  await assert.rejects(db.query('select public.orxelia_save_subscription_snapshot($1,0,$2)',[contract,JSON.stringify(snapshot)]),/revision conflict/);
  const refunds=[{id:'re_test',invoice_id:'in_test',amount:1000,created:now}];
  for(let i=0;i<2;i++) await db.query("select public.orxelia_record_billing_risk('evt_refund',$1,'charge.refunded',$2)",[contract,JSON.stringify(refunds)]);
  assert.equal((await db.query('select count(*)::int count from public.orxelia_billing_refunds')).rows[0].count,1);
  assert.equal((await db.query('select review_required from public.orxelia_billing_contracts')).rows[0].review_required,true);
  await assert.rejects(db.query("select public.orxelia_record_billing_risk('evt_refund2',$1,'charge.refunded',$2)",[contract,JSON.stringify([{id:'re_over',invoice_id:'in_test',amount:3980,created:now}])]),/exceeds/);
  assert.equal((await db.query('select count(*)::int count from public.orxelia_billing_refunds')).rows[0].count,1);
  await db.query('select public.partner_link_finish_stripe_event($1,$2,true)',['evt_test',next.claim_token]);
  assert.equal((await db.query('select * from public.partner_link_claim_stripe_event(false)')).rows.length,0);
  await db.exec('set role authenticated');
  const allowed=()=>db.query('select public.orxelia_has_app_access($1,$2) allowed',[customer,'partner-link']);
  assert.equal((await allowed()).rows[0].allowed,true);
  await db.exec('set role service_role');
  await db.query('select public.orxelia_save_subscription_snapshot($1,1,$2)',[contract,JSON.stringify({...snapshot,status:'past_due',paid_until:now-1})]);
  await db.exec('set role authenticated');
  assert.equal((await allowed()).rows[0].allowed,false);
  await db.exec('set role service_role');
  await db.query('select public.orxelia_save_subscription_snapshot($1,2,$2)',[contract,JSON.stringify(snapshot)]);
  await db.exec('set role authenticated');
  assert.equal((await allowed()).rows[0].allowed,true);
  await db.exec('set role service_role');
  await db.query('select public.orxelia_save_subscription_snapshot($1,3,$2)',[contract,JSON.stringify({...snapshot,status:'canceled'})]);
  await db.exec('set role authenticated');
  assert.equal((await allowed()).rows[0].allowed,false);
  await db.exec(`reset role;create schema vault;create schema net;create schema cron;
    create table vault.decrypted_secrets(name text primary key,decrypted_secret text);
    create table cron.job(jobid bigint generated always as identity,jobname text,schedule text,command text);
    create function cron.unschedule(bigint) returns boolean language plpgsql as $$begin delete from cron.job where jobid=$1;return found;end$$;
    create function cron.schedule(text,text,text) returns bigint language sql as $$insert into cron.job(jobname,schedule,command) values($1,$2,$3) returning jobid$$;
    create function net.http_post(url text,headers jsonb,body jsonb,timeout_milliseconds integer) returns bigint language sql as $$select 1::bigint$$;`);
  await db.exec(fs.readFileSync(new URL('worker-schedule.sql',root),'utf8'));
  assert.equal((await db.query("select count(*)::int count from cron.job where jobname='partner-link-billing-worker'")).rows[0].count,1);
  await assert.rejects(db.query('select public.partner_link_run_billing_worker()'),/configuration/);
  await db.exec(`insert into vault.decrypted_secrets values
    ('partner_link_billing_worker_url','https://fixture.supabase.co/functions/v1/partner-link-billing-worker'),
    ('partner_link_billing_worker_token','test-token-for-local-schedule-only-000000');`);
  assert.equal((await db.query('select public.partner_link_run_billing_worker() request')).rows[0].request,1);
  await db.exec('set role authenticated');
  await assert.rejects(db.query('select public.partner_link_run_billing_worker()'),/permission denied/);
  console.log('PASS: local PostgreSQL queue/retry, atomic snapshots, refunds, access recovery/cancellation and schedule SQL with a local HTTP stub');
});
