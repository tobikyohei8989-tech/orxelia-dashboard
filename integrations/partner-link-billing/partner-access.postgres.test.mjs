import assert from 'node:assert/strict';
import fs from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
import test from 'node:test';
test('tenant data access, legacy use and separate branding',async t=>{
  const db=new PGlite();
  t.after(()=>db.close());
  const founder='00000000-0000-0000-0000-000000000001';
  const owner='00000000-0000-0000-0000-000000000002';
  const worker='00000000-0000-0000-0000-000000000003';
  const outsider='00000000-0000-0000-0000-000000000004';
  await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;create schema auth;
    create table auth.users(id uuid primary key,email_confirmed_at timestamptz default now());
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema auth to authenticated;
    insert into auth.users(id) values ('${founder}'),('${owner}'),('${worker}'),('${outsider}');
    create table public.tobita_match_members(user_id uuid primary key,owner_id uuid,role text,display_name text);
    create table public.tobita_match_requests(id uuid primary key default gen_random_uuid(),owner_id uuid,worker_id uuid);
    create table public.tobita_match_availability(id uuid primary key default gen_random_uuid(),owner_id uuid,worker_id uuid);
    create table public.tobita_match_events(id uuid primary key default gen_random_uuid(),owner_id uuid,recipient_id uuid,request_id uuid);
    create table public.tobita_match_invites(id uuid primary key default gen_random_uuid(),owner_id uuid);
    create table public.tobita_match_attendance(request_id uuid primary key);
    create table public.tobita_match_attendance_history(request_id uuid);
    create table public.tobita_match_branding(id integer primary key,company_line1 text,company_line2 text,logo_data text,updated_at timestamptz);
    insert into public.tobita_match_branding values(1,'社内','既存会社',null,now());
    insert into public.tobita_match_members values('${founder}','${founder}','admin','既存管理者');
    alter table public.tobita_match_requests enable row level security;
    grant select on public.tobita_match_requests to authenticated;
    grant select on public.tobita_match_members to authenticated;
    create policy request_owner on public.tobita_match_requests for select to authenticated using (owner_id=auth.uid() or worker_id=auth.uid());
    create function public.fixture_send(p_owner uuid,p_worker uuid) returns uuid language plpgsql security definer as $$
    declare result uuid;begin
      insert into public.tobita_match_requests(owner_id,worker_id) values(p_owner,p_worker) returning id into result;return result;
    end $$;
    select set_config('request.jwt.claim.sub','${founder}',false);`);
  const root=new URL('./',import.meta.url);
  for(const file of ['customer-management.sql','registration.sql','partner-access.sql'])await db.exec(fs.readFileSync(new URL(file,root),'utf8'));
  await db.exec('set role authenticated');
  assert.equal((await db.query('select public.orxelia_partner_link_allowed($1) allowed',[founder])).rows[0].allowed,true);
  await db.query('select public.fixture_send($1,$2)',[founder,worker]);
  await assert.rejects(db.query("select public.orxelia_register_partner_company('既存会社')"),/社内/);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[owner]);
  const customer=(await db.query("select public.orxelia_register_partner_company('新規の会社') id")).rows[0].id;
  assert.equal((await db.query('select public.orxelia_partner_link_billing_status() status')).rows[0].status.allowed,false);
  await assert.rejects(db.query('select public.fixture_send($1,$2)',[owner,worker]),/利用状態/);
  await db.exec('reset role');
  await db.query("insert into public.tobita_match_members values($1,$2,'worker','職人')",[worker,owner]);
  await db.query("insert into public.orxelia_billing_contracts(customer_id,app_id,monthly_amount_jpy,status,trial_until) values($1,'partner-link',3980,'trialing',now()+interval '1 day')",[customer]);
  await db.exec('set role authenticated');
  await db.query('select public.fixture_send($1,$2)',[owner,worker]);
  assert.equal((await db.query('select count(*)::int count from public.tobita_match_requests')).rows[0].count,1);
  await db.query("select public.orxelia_save_partner_link_brand('新規','テスト会社',null)");
  assert.equal((await db.query('select public.orxelia_partner_link_brand() brand')).rows[0].brand.company_line2,'テスト会社');
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[worker]);
  assert.equal((await db.query('select public.orxelia_partner_link_allowed($1) allowed',[owner])).rows[0].allowed,true);
  await assert.rejects(db.query("select public.orxelia_save_partner_link_brand('他社','変更',null)"),/管理者/);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[outsider]);
  assert.equal((await db.query('select count(*)::int count from public.tobita_match_requests')).rows[0].count,0);
  await assert.rejects(db.query('select public.fixture_send($1,$2)',[owner,worker]),/利用状態/);
  await db.exec('reset role');
  await db.query("update public.orxelia_billing_contracts set status='canceled' where customer_id=$1",[customer]);
  await db.exec('set role authenticated');
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[owner]);
  assert.equal((await db.query('select count(*)::int count from public.tobita_match_requests')).rows[0].count,0);
  await assert.rejects(db.query('select public.fixture_send($1,$2)',[owner,worker]),/利用状態/);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[founder]);
  assert.equal((await db.query('select public.orxelia_partner_link_billing_status() status')).rows[0].status.allowed,true);
  assert.equal((await db.query('select public.orxelia_partner_link_brand() brand')).rows[0].brand.company_line2,'既存会社');
  console.log('PASS: legacy internal use, new-company trial, worker scope, foreign-company denial, canceled-contract reads/writes, and separate company branding');
});
