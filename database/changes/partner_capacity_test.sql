-- All fixture writes, events, and claim changes are rolled back inside the subtransaction.
create or replace function pg_temp.check_partner_capacity() returns text language plpgsql as $$
declare w uuid; a uuid; d date:=((now() at time zone 'Asia/Tokyo')::date+400); r uuid; blocked boolean; before_requests bigint; before_availability bigint; before_events bigint;
begin
 select user_id,owner_id into w,a from public.tobita_match_members where role='worker' limit 1;
 if w is null then raise exception 'No worker fixture available'; end if;
 select count(*) into before_requests from public.tobita_match_requests;
 select count(*) into before_availability from public.tobita_match_availability;
 select count(*) into before_events from public.tobita_match_events;
 begin
  perform set_config('request.jwt.claim.sub',w::text,true);
  perform public.tobita_match_set_capacity(array[d-1,d,d+1,d+2,d+3],'all',3);
  perform set_config('request.jwt.claim.sub',a::text,true);
  perform public.tobita_match_send_capacity(w,'容量テスト（保存しない）',array[d,d+1],'all','07:30','テスト',2);
  blocked:=false;
  begin perform public.tobita_match_send_capacity(w,'上限超過',array[d],'all','07:30','テスト',2); exception when others then blocked:=true; end;
  assert blocked,'Overbooking must be rejected';
  perform public.tobita_match_send_capacity(w,'残り1人',array[d],'am','07:30','テスト',1);
  blocked:=false;
  begin perform public.tobita_match_send_capacity(w,'全日不可',array[d],'all','07:30','テスト',1); exception when others then blocked:=true; end;
  assert blocked,'All-day availability must use the minimum of morning and afternoon';
  blocked:=false;
  begin perform public.tobita_match_send_capacity(w,'一括失敗',array[d-1,d+1],'all','07:30','テスト',2); exception when others then blocked:=true; end;
  assert blocked,'Multi-date overbooking must fail';
  assert not exists(select 1 from public.tobita_match_requests where worker_id=w and work_date=d-1),'A failed batch must not leave partial requests';
  perform set_config('request.jwt.claim.sub',w::text,true);
  for r in select id from public.tobita_match_requests where worker_id=w and work_date in(d,d+1) and status='pending' loop perform public.tobita_match_respond(r,true); end loop;
  assert (select sum(headcount)=3 from public.tobita_match_requests where worker_id=w and work_date=d and status='confirmed'),'Partial reservations must both confirm';
  blocked:=false;
  begin perform public.tobita_match_set_capacity(array[d],'all',2); exception when others then blocked:=true; end;
  assert blocked,'Capacity must not fall below reserved headcount';
  perform public.tobita_match_set_capacity(array[d],'all',4);
  perform set_config('request.jwt.claim.sub',a::text,true);
  select id into r from public.tobita_match_requests where worker_id=w and work_date=d and slot='all';
  perform public.tobita_match_cancel(r);
  perform public.tobita_match_send_capacity(w,'取消で空きが戻る',array[d],'all','07:30','テスト',3);
  perform set_config('request.jwt.claim.sub',w::text,true);
  select id into r from public.tobita_match_requests where worker_id=w and work_date=d and status='pending';
  perform public.tobita_match_respond(r,false);
  perform set_config('request.jwt.claim.sub',a::text,true);
  perform public.tobita_match_send_capacity(w,'辞退で空きが戻る',array[d],'all','07:30','テスト',3);
  perform public.tobita_match_send_details(w,'旧クライアント互換',array[d+3],'am','07:30','テスト');
  assert (select headcount=1 from public.tobita_match_requests where worker_id=w and work_date=d+3),'Old clients must default to one person';
  blocked:=false;
  begin perform public.tobita_match_send_capacity(gen_random_uuid(),'他社',array[d],'am','07:30','テスト',1); exception when others then blocked:=true; end;
  assert blocked,'Non-team worker must be rejected';
  perform set_config('request.jwt.claim.sub','',true);
  blocked:=false;
  begin perform public.tobita_match_set_capacity(array[d],'all',4); exception when others then blocked:=true; end;
  assert blocked,'Unauthenticated writes must be rejected';
  assert not has_function_privilege('anon','public.tobita_match_send_capacity(uuid,text,date[],text,text,text,integer)','execute'),'Anonymous RPC access must be denied';
  raise exception using errcode='ZX001',message='ROLLBACK_SUCCESS';
 exception when sqlstate 'ZX001' then null;
 end;
 assert (select count(*)=before_requests from public.tobita_match_requests),'Requests must be unchanged after test';
 assert (select count(*)=before_availability from public.tobita_match_availability),'Availability must be unchanged after test';
 assert (select count(*)=before_events from public.tobita_match_events),'Events must be unchanged after test';
 return 'PASS: capacity, partial booking, acceptance, overbooking guard, half-days, atomic batch, capacity reduction, cancellation/decline release, legacy client, authorization; all test data rolled back';
end $$;
select pg_temp.check_partner_capacity();
