import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('experiments/tobita-partner-schedule/app.html','utf8');
const helpers=html.slice(html.indexOf('function slotCapacity('),html.indexOf('function jpHolidays('));
const context=vm.createContext({availability:[],requests:[],Number,Math,member:{role:'worker',user_id:'w'},workers:[]});
vm.runInContext(helpers,context);
const remaining=slot=>vm.runInContext(`slotRemaining('w','2026-11-12','${slot}')`,context);
context.availability=[{worker_id:'w',work_date:'2026-11-12',slot:'am',capacity:3},{worker_id:'w',work_date:'2026-11-12',slot:'pm',capacity:2}];
assert.equal(remaining('all'),2);
context.requests=[{worker_id:'w',work_date:'2026-11-12',slot:'all',status:'confirmed',headcount:1},{worker_id:'w',work_date:'2026-11-12',slot:'am',status:'pending',headcount:1}];
assert.equal(remaining('am'),1);assert.equal(remaining('pm'),1);assert.equal(remaining('all'),1);
context.requests[1].status='declined';assert.equal(remaining('am'),2);
context.requests[0].status='cancelled';assert.equal(remaining('all'),2);
context.availability[0].capacity=undefined;context.availability[1].capacity=undefined;
assert.equal(remaining('all'),1);
context.requests=[{worker_id:'w',work_date:'2026-11-12',slot:'am',status:'pending'}];
assert.equal(remaining('am'),0);assert.equal(remaining('pm'),1);
assert.equal(vm.runInContext("slotFree('w','2026-11-12','all',0)",context),false);
for(const marker of ['tobita_match_set_capacity','tobita_match_send_capacity','requestHeadcount','availableHeadcount','selectMatchedDay'])assert.ok(html.includes(marker));
console.log('PASS: remaining headcount, half-day limits, pending reservations, release, legacy one-person defaults and UI wiring');
